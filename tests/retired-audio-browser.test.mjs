import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { buildPreview } from '../scripts/build.mjs';
import { launchChromium } from '../scripts/qa/browser.mjs';
import { startNavServer } from '../scripts/qa/nav-layout.mjs';
import { openPage } from '../scripts/qa/open-page.mjs';
import { previewCall } from '../scripts/preview-server.mjs';

test('materials, import and settings expose no retired recording modules', { timeout: 120000 }, async (t) => {
  const browser = await launchChromium();
  t.after(() => browser.close());
  const dist = await mkdtemp(join(tmpdir(), 'retired-audio-dist-'));
  await buildPreview({ outdir: dist });
  const running = await startNavServer({ distDir: dist });
  t.after(() => running.close());
  await previewCall(running.server, 'sample.load', {});
  const page = await browser.newPage({ locale: 'zh-CN', reducedMotion: 'reduce' });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(running.server.url);
  await page.locator('.sidebar').first().waitFor();
  const later = page.getByRole('button', { name: '以后再说' });
  if (await later.count()) await later.click();
  await openPage(page, 'sources');
  assert.deepEqual(await page.locator('.space-header__view').evaluateAll(tabs => tabs.map(tab => tab.dataset.view)), ['sources', 'generate']);
  await page.getByText('资料处理流程', { exact: true }).click();
  assert.deepEqual(await page.locator('.loop-row select option').allTextContents(), ['文档', 'PDF 转换']);
  await page.getByRole('button', { name: '添加资料', exact: true }).first().click();
  const dialog = page.getByRole('dialog');
  await dialog.waitFor();
  assert.equal(await dialog.getByRole('button', { name: '音频 / 录音', exact: true }).count(), 0);
  const accept = await dialog.locator('input[type=file]').first().getAttribute('accept');
  assert.match(accept, /\.pdf/);
  assert.doesNotMatch(accept, /\.mp3|\.wav|\.srt|\.vtt/);
  await page.keyboard.press('Escape');
  await openPage(page, 'settings');
  await page.locator('.settings-nav').waitFor();
  assert.equal(await page.locator('.settings-nav [data-category="audio"]').count(), 0);
  assert.equal(await page.locator('.settings-nav [data-category="mineru"]').count(), 1);
  assert.deepEqual(errors, []);
});
