import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { StudyService } from '../lib/service.js';
import { buildPreview } from '../scripts/build.mjs';
import { createPreviewServer, previewCall } from '../scripts/preview-server.mjs';
import { launchChromium } from '../scripts/qa/browser.mjs';
import { openPage } from '../scripts/qa/open-page.mjs';
import { outlineLibrary, COURSE } from './helpers/course-outline-library.mjs';
import { bookModel } from './helpers/course-book-model.mjs';

test('outline and skeleton work end to end in a preview without chat or agents', { timeout: 120000 }, async t => {
  const base = await mkdtemp(join(tmpdir(), 'knowledge-browser-'));
  const libraryRoot = join(base, 'library'), distDir = join(base, 'dist');
  const seed = new StudyService(libraryRoot), library = outlineLibrary();
  await seed.store.update(s => {
    s.sources.push(...library.sources.filter(source => source.id.startsWith('document-l1-p')).slice(0, 2));
    s.decks.push({ ...library.decks.find(deck => deck.id === 'deck-l1'), cards: library.decks.find(deck => deck.id === 'deck-l1').cards.slice(0, 3) });
  });
  await seed.dispose();
  const book = bookModel();
  let generations = 0;
  const model = async (system, prompt, options) => {
    if (!system.startsWith('Organize learning data')) return book.complete(system, prompt, options);
    const input = JSON.parse(prompt);
    if (input.mode === 'groups') return JSON.stringify({ groups: [{ title: '架构基础', topics: input.topics.map(topic => topic.key) }] });
    generations++;
    if (generations === 1) await new Promise(resolve => setTimeout(resolve, 2000));
    if (input.instruction === '测试模型失败') throw new Error('模型服务测试故障');
    return JSON.stringify({ title: '架构概念脉络', overview: input.instruction || '学习架构决策的依据', nodes: [{ id: 'root', term: '架构决策', meaning: '记录决策及其原因', cards: input.context.cards.map(card => card.cardId) }], relations: [] });
  };
  await buildPreview({ outdir: distDir });
  const server = await createPreviewServer({ libraryRoot, distDir, home: join(base, 'home'), port: 0, model });
  t.after(() => server.close());
  await previewCall(server, 'focus.set', { course: COURSE });
  const browser = await launchChromium();
  t.after(() => browser.close());
  const page = await browser.newPage({ reducedMotion: 'reduce', viewport: { width: 1440, height: 1000 } });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(server.url);
  await page.locator('.sidebar').first().waitFor();
  const later = page.getByRole('button', { name: '以后再说' });
  if (await later.count()) await later.click();
  await openPage(page, 'book');
  await page.getByRole('button', { name: '从资料生成大纲', exact: true }).click();
  await page.getByRole('button', { name: '重新整理大纲', exact: true }).waitFor({ timeout: 30000 });
  assert.ok(await page.locator('.loop-row h2').count());
  await page.getByRole('searchbox', { name: '筛选本页知识点' }).fill('Foundations');
  assert.equal(await page.locator('.loop-row h2').count(), 1);
  await page.getByRole('searchbox', { name: '筛选本页知识点' }).fill('');
  await page.getByRole('button', { name: '生成或更新阅读内容', exact: true }).click();
  await page.locator('.loop-tabs').getByRole('button', { name: '阅读', exact: true }).click();
  await page.getByText(/explained for a beginner/).first().waitFor({ timeout: 30000 });
  await page.getByRole('button', { name: '学这个知识点', exact: true }).first().click();
  await page.locator('.loop-session textarea').waitFor();
  await page.keyboard.press('Escape');
  await page.screenshot({ path: join(base, 'outline.png'), fullPage: true });
  await openPage(page, 'skeleton');
  await page.getByRole('checkbox', { name: /^选择主题 / }).first().check();
  await page.getByRole('button', { name: '生成知识骨架', exact: true }).click();
  await openPage(page, 'book');
  await openPage(page, 'skeleton');
  await page.getByText('正在后台整理，可继续浏览', { exact: true }).waitFor();
  await page.locator('.sk-view h3').filter({ hasText: '架构概念脉络' }).waitFor({ timeout: 30000 });
  await page.getByRole('textbox', { name: '调整知识骨架' }).fill('补充架构决策与证据的关系');
  await page.getByRole('button', { name: '更新结构', exact: true }).click();
  await page.locator('.sk-overview').filter({ hasText: '补充架构决策与证据的关系' }).waitFor({ timeout: 30000 });
  assert.equal(generations, 2);
  await page.getByRole('textbox', { name: '调整知识骨架' }).fill('测试模型失败');
  await page.getByRole('button', { name: '更新结构', exact: true }).click();
  await page.getByText('生成未完成，可调整后重新生成', { exact: true }).waitFor({ timeout: 30000 });
  assert.match(await page.locator('.sk-overview').textContent(), /补充架构决策与证据的关系/);
  await page.getByRole('textbox', { name: '调整知识骨架' }).fill('恢复后调整');
  await page.getByRole('button', { name: '更新结构', exact: true }).click();
  await page.locator('.sk-overview').filter({ hasText: '恢复后调整' }).waitFor({ timeout: 30000 });
  await page.getByRole('button', { name: '✦ AI 归并主题', exact: true }).click();
  await page.getByText('架构基础', { exact: true }).first().waitFor({ timeout: 30000 });
  await page.getByRole('button', { name: '结构图', exact: true }).click();
  await page.getByRole('textbox', { name: '查找概念', exact: true }).fill('架构决策');
  await page.locator('.skc-results').getByRole('button', { name: '架构决策', exact: true }).click();
  await page.getByRole('heading', { name: '调整这个概念', exact: true }).waitFor();
  assert.equal(await page.getByRole('button', { name: '为它补题', exact: true }).count(), 0);
  await page.screenshot({ path: join(base, 'skeleton.png'), fullPage: true });
  assert.equal(await page.getByRole('button', { name: '在对话中生成骨架', exact: true }).count(), 0);
  assert.deepEqual(errors, []);
  console.log(`Knowledge UI evidence: ${base}`);
});
